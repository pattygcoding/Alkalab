// Headless smoke test for the WebAssembly build.
//
// It loads the *same* module the browser loads (`web/pkg`, the `--target web`
// output), wraps the exported linear memory in a `Uint8ClampedArray` exactly like
// the canvas renderer does, and then drives the engine: paint, step, chemistry,
// undo, explode.
//
//   node tests/wasm/smoke.mjs
//
// Run `npm run build` first.

import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import init, { Engine } from '../../web/pkg/alkalab.js';

const here = dirname(fileURLToPath(import.meta.url));
const wasmBytes = await readFile(join(here, '../../web/pkg/alkalab.wasm'));
const wasm = await init({ module_or_path: wasmBytes });

const WIDTH = 320;
const HEIGHT = 200;

/** Rebuilds the pixel view, as the browser must whenever the memory grows. */
let buffer = null;
let pixels = null;
function pixelView(engine) {
  if (wasm.memory.buffer !== buffer) {
    buffer = wasm.memory.buffer;
    pixels = new Uint8ClampedArray(buffer, engine.pixel_ptr, engine.pixel_len);
  }
  return pixels;
}

function pixelAt(view, x, y) {
  const offset = (y * WIDTH + x) * 4;
  return [view[offset], view[offset + 1], view[offset + 2], view[offset + 3]];
}

function hex(bytes) {
  return `#${bytes
    .slice(0, 3)
    .map((b) => b.toString(16).padStart(2, '0'))
    .join('')}`;
}

const started = performance.now();
const engine = new Engine(WIDTH, HEIGHT, 20240729);
console.log(`engine created in ${(performance.now() - started).toFixed(1)} ms`);

// --- the shared buffer -------------------------------------------------------
assert.equal(engine.width, WIDTH);
assert.equal(engine.height, HEIGHT);
assert.equal(engine.pixel_len, WIDTH * HEIGHT * 4);
assert.equal(engine.frame, 0);

let view = pixelView(engine);
assert.equal(view.length, WIDTH * HEIGHT * 4);
assert.equal(view.byteLength, engine.pixel_len);
for (let i = 3; i < view.length; i += 4) {
  assert.equal(view[i], 255, 'every pixel must be opaque');
}
console.log(`shared pixel buffer: ${view.length} bytes, viewed with zero copies`);

// --- the palette is generated by Rust ---------------------------------------
const catalog = JSON.parse(engine.element_catalog());
assert.equal(catalog.length, 32, 'the full element table should be exposed');
for (const entry of catalog) {
  assert.equal(typeof entry.id, 'number');
  assert.match(entry.color, /^#[0-9a-f]{6}$/);
  assert.ok(entry.name.length > 0 && entry.desc.length > 0);
}
const idOf = (name) => {
  const entry = catalog.find((c) => c.name === name);
  assert.ok(entry, `missing element ${name}`);
  return entry.id;
};
console.log(
  `palette: ${catalog.length} elements, from ${catalog[0].name} to ${catalog.at(-1).name}`,
);

// --- painting shows up in the pixels ----------------------------------------
// Wall has no per-pixel speckle, so its colour must come through untouched.
engine.paint_rect(10, 10, 20, 20, idOf('Wall'));
view = pixelView(engine);
const wall = catalog.find((c) => c.name === 'Wall');
assert.equal(hex(pixelAt(view, 15, 15)), wall.color, 'the pixels mirror the grid');
assert.equal(pixelAt(view, 15, 15)[3], 255);
engine.clear();
assert.equal(engine.particle_count, 0);

// --- falling sand ------------------------------------------------------------
const SAND = idOf('Sand');
engine.paint(160, 10, 4, SAND);
const painted = engine.count_of(SAND);
assert.ok(painted > 20, 'the brush should paint a disc');

engine.step();
assert.equal(engine.element_at(160, 11), SAND, 'one tick, one cell of fall');

for (let i = 0; i < 400; i += 1) {
  engine.step();
}
assert.equal(engine.count_of(SAND), painted, 'sand is conserved');
assert.equal(engine.element_at(160, HEIGHT - 1), SAND, 'sand reaches the floor');
console.log(`sand settled at y = ${HEIGHT - 1} after ${engine.frame} ticks`);

// --- chemistry ---------------------------------------------------------------
engine.clear();
const WATER = idOf('Water');
const SODIUM = idOf('Sodium');
engine.paint_rect(40, 150, 280, 195, WATER);
engine.paint(160, 140, 2, SODIUM);

let reaction = null;
const chemStarted = performance.now();
// Keep ticking the whole window: the first log hit is recorded but the metal
// keeps reacting for a few ticks after that (each grain explodes separately),
// so stop the search early but not the simulation.
for (let i = 0; i < 300; i += 1) {
  engine.step();
  if (reaction === null) {
    reaction =
      JSON.parse(engine.reactions()).find((entry) =>
        entry.equation.includes('2 Na + 2 H2O'),
      ) ?? null;
  }
}
assert.ok(reaction, 'sodium in water must be recorded in the reaction log');
assert.equal(engine.count_of(SODIUM), 0, 'the metal is consumed');
console.log(
  `reaction after ${(performance.now() - chemStarted).toFixed(1)} ms: "${reaction.equation}"`,
);

// --- the boom tool and undo --------------------------------------------------
engine.clear();
engine.paint_rect(100, 80, 220, 120, idOf('Wood'));
engine.paint_rect(140, 100, 180, 105, idOf('TNT'));
const tntBefore = engine.count_of(idOf('TNT'));
const woodBefore = engine.count_of(idOf('Wood'));
assert.ok(tntBefore > 200 && woodBefore > 1000);

// Snapshot the loaded scene, then blow it up: one undo must bring it back.
engine.snapshot();
engine.detonate(160, 102, 14);
assert.ok(engine.can_undo, 'the charge should be undoable');
for (let i = 0; i < 60; i += 1) {
  engine.step();
}
assert.ok(engine.count_of(idOf('TNT')) < tntBefore, 'the charge detonates');
assert.ok(engine.count_of(idOf('Wood')) < woodBefore, 'the blast wrecks the timber');

assert.ok(engine.undo(), 'undo is available');
assert.equal(engine.count_of(idOf('TNT')), tntBefore, 'undo puts the charge back');
assert.equal(engine.count_of(idOf('Wood')), woodBefore, 'and the timber too');

// --- throughput --------------------------------------------------------------
engine.clear();
for (let i = 0; i < 24; i += 1) {
  engine.paint_rect(i * 12, 20, i * 12 + 8, 180, catalog[i + 1].id);
}
const benchStart = performance.now();
const ticks = 200;
for (let i = 0; i < ticks; i += 1) {
  engine.step();
}
const ms = performance.now() - benchStart;
console.log(
  `${ticks} ticks of a busy ${WIDTH}x${HEIGHT} world in ${ms.toFixed(1)} ms ` +
    `(${(ms / ticks).toFixed(3)} ms/tick, ~${Math.round(1000 / (ms / ticks))} ticks/s)`,
);

// --- invariants that must survive all of the above ---------------------------
view = pixelView(engine);
assert.equal(view.length, WIDTH * HEIGHT * 4);
assert.equal(pixelAt(view, 0, 0)[3], 255);
assert.equal(typeof engine.hash, 'number');
console.log('\nall wasm smoke tests passed');

