// Build the Nim engine to wasm and generate the browser glue.
//
//   node nim/build.mjs
//
// Outputs:
//   nim/src/alkalab.wasm        raw wasm module
//   nim/web/pkg/alkalab.wasm    module served by the page
//   nim/web/pkg/alkalab.js      ES module glue (init + Engine)
//   nim/web/{index.html,main.js,style.css}  copied from the shared web/ folder

import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const nimDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(nimDir, '..');
const srcDir = path.join(nimDir, 'src');
const webDir = path.join(nimDir, 'web');
const pkgDir = path.join(webDir, 'pkg');
const includeDir = path.join(srcDir, 'wasm_include').replaceAll('\\', '/');

const nim = process.platform === 'win32' ? 'nim.exe' : 'nim';
const passC = `-I${includeDir} --target=wasm32-unknown-unknown`;
const passL = '--target=wasm32-unknown-unknown -nostdlib -Wl,--no-entry ' +
  '-Wl,--export-all -Wl,--export-memory ' +
  '-Wl,--initial-memory=100663296 -Wl,--max-memory=268435456';

const args = [
  'c',
  '--cpu:wasm32',
  '--os:standalone',
  '--cc:clang',
  '--noMain:on',
  '-d:release',
  '-d:standalone',
  '-d:useMalloc',
  '--mm:arc',
  '--threads:off',
  `--passC:${passC}`,
  `--passL:${passL}`,
  '--out:alkalab.wasm',
  'alkalab.nim',
];

console.log(`[alkalab] ${nim} ${args.join(' ')}`);
const build = spawnSync(nim, args, { cwd: srcDir, stdio: 'inherit' });
if (build.status !== 0) {
  process.exit(build.status ?? 1);
}

const wasmPath = path.join(srcDir, 'alkalab.wasm');
if (!fs.existsSync(wasmPath)) {
  console.error('[alkalab] wasm output was not produced');
  process.exit(1);
}

fs.mkdirSync(pkgDir, { recursive: true });
fs.copyFileSync(wasmPath, path.join(pkgDir, 'alkalab.wasm'));

const glue = String.raw`// Alkalab Nim engine glue. Generated by nim/build.mjs.
//
// The engine owns the simulation state and the RGBA pixel buffer inside wasm
// linear memory. This module only instantiates the module and wraps the raw
// C-ABI exports in a small JS class.

let wasm = null;
let memory = null;

function decode(ptr, len) {
  if (!ptr || !len) return '';
  return new TextDecoder().decode(new Uint8Array(memory.buffer, ptr, len));
}

export default async function init(options = {}) {
  const source = options?.module_or_path ?? options;
  let bytes;
  if (source instanceof ArrayBuffer) {
    bytes = source;
  } else if (ArrayBuffer.isView(source)) {
    bytes = source.buffer;
  } else if (typeof source === 'string' || source instanceof URL) {
    bytes = await (await fetch(source)).arrayBuffer();
  } else {
    const url = new URL('./alkalab.wasm', import.meta.url);
    bytes = await (await fetch(url)).arrayBuffer();
  }
  const { instance } = await WebAssembly.instantiate(bytes, {});
  wasm = instance.exports;
  memory = wasm.memory;
  if (wasm.__wasm_call_ctors) wasm.__wasm_call_ctors();
  return { memory, ...wasm };
}

export class Engine {
  constructor(width, height, seed) {
    if (!wasm) throw new Error('call init() before new Engine()');
    this._ptr = wasm.engine_new(width | 0, height | 0, seed >>> 0);
  }

  get width() { return wasm.engine_width(this._ptr); }
  get height() { return wasm.engine_height(this._ptr); }
  get frame() { return wasm.engine_frame(this._ptr); }
  get pixel_ptr() { return wasm.engine_pixel_ptr(this._ptr); }
  get pixel_len() { return wasm.engine_pixel_len(this._ptr); }
  get particle_count() { return wasm.engine_particle_count(this._ptr); }
  get can_undo() { return wasm.engine_can_undo(this._ptr); }
  get hash() { return wasm.engine_hash(this._ptr); }

  step() { wasm.engine_step(this._ptr); }
  step_n(ticks) { wasm.engine_step_n(this._ptr, ticks >>> 0); }
  paint(x, y, radius, element) { return wasm.engine_paint(this._ptr, x | 0, y | 0, radius | 0, element & 0xff); }
  paint_line(x0, y0, x1, y1, radius, element) {
    return wasm.engine_paint_line(this._ptr, x0 | 0, y0 | 0, x1 | 0, y1 | 0, radius | 0, element & 0xff);
  }
  paint_rect(x0, y0, x1, y1, element) {
    return wasm.engine_paint_rect(this._ptr, x0 | 0, y0 | 0, x1 | 0, y1 | 0, element & 0xff);
  }
  detonate(x, y, radius) { wasm.engine_detonate(this._ptr, x | 0, y | 0, radius | 0); }
  clear() { wasm.engine_clear(this._ptr); }
  snapshot() { wasm.engine_snapshot(this._ptr); }
  undo() { return wasm.engine_undo(this._ptr); }
  element_at(x, y) { return wasm.engine_element_at(this._ptr, x | 0, y | 0); }
  count_of(element) { return wasm.engine_count_of(this._ptr, element & 0xff); }
  element_catalog() {
    return decode(wasm.engine_catalog_ptr(this._ptr), wasm.engine_catalog_len(this._ptr));
  }
  reactions() {
    return decode(wasm.engine_reactions_ptr(this._ptr), wasm.engine_reactions_len(this._ptr));
  }
  free() {
    if (this._ptr) wasm.engine_free(this._ptr);
    this._ptr = 0;
  }
}
`;

fs.writeFileSync(path.join(pkgDir, 'alkalab.js'), glue);

for (const file of ['index.html', 'main.js', 'style.css']) {
  const from = path.join(repoRoot, 'web', file);
  const to = path.join(webDir, file);
  if (!fs.existsSync(from)) continue;
  fs.copyFileSync(from, to);
  if (file === 'index.html') {
    let html = fs.readFileSync(to, 'utf8');
    html = html
      .replaceAll('Rust + WebAssembly', 'Nim + WebAssembly')
      .replaceAll('written in Rust', 'written in Nim')
      .replaceAll('Rust cellular automaton', 'Nim cellular automaton')
      .replaceAll('Rust renders straight into a', 'Nim renders straight into a')
      .replaceAll('Built with Rust + <code>wasm-bindgen</code>', 'Built with Nim + <code>wasm</code>')
      .replaceAll('<code>std</code> Rust', 'Nim <code>std</code>')
      .replaceAll('<code>cargo test</code>', '<code>nim c -r</code>');
    fs.writeFileSync(to, html);
  } else if (file === 'main.js') {
    fs.writeFileSync(to, fs.readFileSync(to, 'utf8').replaceAll('Rust', 'Nim'));
  }
}

const bytes = fs.statSync(path.join(pkgDir, 'alkalab.wasm')).size;
console.log(`[alkalab] wasm ${(bytes / 1024).toFixed(1)} KiB -> nim/web/pkg/alkalab.wasm`);
console.log('[alkalab] serve the page with: node scripts/serve.mjs nim/web');
